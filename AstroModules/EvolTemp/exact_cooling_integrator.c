/* ============================================================================
 * Simple Euler Integration (for comparison)
 * ============================================================================ */
double euler_integrate(double nH, double Z, double T_init, double dt, double *T_final) {
    /* Get net cooling rate */
    double Lambda = interp_net_rate(nH, Z, T_init);
    
    /* Calculate gas mass density from nH using proper mass fractions */
    double rho = nH_to_rho(nH, Z);
    (void)rho;  /* Used when USE_GETMU is defined */
    
    /* Get mean molecular weight */
    double mu;
#ifdef USE_GETMU
    mu = get_mean_molecular_weight(rho, T_init, Z);
#else
//    mu = calc_mean_molecular_weight(T_init, Z);
    mu = calc_mean_molecular_weight(T_init, Z);
    mu = calculate_mu(rho,T_init, Z);
#endif
    
    /* du/dt = -Lambda */
    double u = T_to_u(T_init, mu);
    double u_new = u - Lambda * dt;
    
    /* Prevent negative internal energy */
    if (u_new < 0) u_new = u * 0.01;
    
    *T_final = u_to_T(u_new, mu);
    return *T_final - T_init;
}

