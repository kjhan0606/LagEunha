#include "getMU.h"

/* ============================================================================
 * Physical Constants (CGS units)
 * ============================================================================ */
#define K_BOLTZMANN     1.3806504e-16   /* Boltzmann constant [erg/K] */
#define M_PROTON        1.6726219e-24   /* Proton mass [g] */
#define M_HELIUM        (4.002602 * M_PROTON)  /* Helium atom mass [g] */
#define GAMMA           (5.0/3.0)       /* Adiabatic index for monatomic ideal gas */
#define YEAR_IN_SEC     3.15576e7       /* Seconds per year */
#define MYR_IN_SEC      3.15576e13      /* Seconds per Myr */

/* ============================================================================
 * Primordial Abundances (Big Bang Nucleosynthesis values)
 * ============================================================================ */
#define X_PRIMORDIAL    0.76            /* Primordial hydrogen mass fraction */
#define Y_PRIMORDIAL    0.24            /* Primordial helium mass fraction */
#define Z_SOLAR         0.0134          /* Solar metallicity (Asplund et al. 2009) */

/* ============================================================================
 * Configuration - must match cooling_rate_mpi.c
 * ============================================================================ */
#include "cooling_rate_mpi.h"

/* Tolerance for floating point comparisons */
#define EPSILON         1.0e-30
#define REL_TOLERANCE   1.0e-8

/* ============================================================================
 * Mass Fraction Structure
 * ============================================================================ */
typedef struct {
    double X;       /* Hydrogen mass fraction */
    double Y;       /* Helium mass fraction */
    double Z;       /* Metal mass fraction */
} MassFractions;

/* ============================================================================
 * Calculate mass fractions from metallicity
 * 
 * Given metallicity Z_metal in solar units:
 *   Z = Z_metal * Z_solar
 *   X = X_primordial * (1 - Z) / (X_primordial + Y_primordial)
 *   Y = Y_primordial * (1 - Z) / (X_primordial + Y_primordial)
 * 
 * This ensures X + Y + Z = 1
 * ============================================================================ */
static MassFractions calc_mass_fractions(double Z_metal) {
    MassFractions mf;
    
    /* Metal mass fraction */
    mf.Z = Z_metal * Z_SOLAR;
    if (mf.Z < 0.0) mf.Z = 0.0;
    if (mf.Z > 1.0) mf.Z = 1.0;
    
    /* Scale primordial abundances to maintain X + Y + Z = 1 */
    double f = (1.0 - mf.Z) / (X_PRIMORDIAL + Y_PRIMORDIAL);
    mf.X = X_PRIMORDIAL * f;
    mf.Y = Y_PRIMORDIAL * f;
    
    return mf;
}

/* ============================================================================
 * Convert hydrogen number density to gas mass density
 * 
 * n_H = rho * X / m_H
 * Therefore: rho = n_H * m_H / X
 * 
 * where X is the hydrogen mass fraction
 * ============================================================================ */
static double nH_to_rho(double nH, double Z_metal) {
    MassFractions mf = calc_mass_fractions(Z_metal);
    return nH * M_PROTON / mf.X;
}

/* ============================================================================
 * Convert gas mass density to hydrogen number density
 * 
 * n_H = rho * X / m_H
 * ============================================================================ */
static double rho_to_nH(double rho, double Z_metal) {
    MassFractions mf = calc_mass_fractions(Z_metal);
    return rho * mf.X / M_PROTON;
}

/* ============================================================================
 * Calculate mean molecular weight
 * 
 * For fully ionized gas:
 *   mu = 1 / (2X + 3Y/4 + Z/2)
 *   (assuming metals have average A/Z ~ 2)
 * 
 * For fully neutral gas:
 *   mu = 1 / (X + Y/4 + Z/A_metal)
 *   where A_metal ~ 16 for typical ISM metals (O, C, N, etc.)
 * 
 * This function provides smooth interpolation between these limits
 * based on temperature.
 * ============================================================================ */
static double calc_mean_molecular_weight(double T, double Z_metal) {
    MassFractions mf = calc_mass_fractions(Z_metal);
    
    /* Ionization transition temperatures */
    const double T_ionize_low = 6000.0;    /* Start of H ionization */
    const double T_ionize_high = 20000.0;  /* Fully ionized */
    
    /* Mean atomic weight of metals (dominated by O, C, N) */
    const double A_metal = 16.0;
    
    /* Fully neutral mean molecular weight */
    /* mu_neutral = 1 / (X + Y/4 + Z/A_metal) */
    double denom_neutral = mf.X + mf.Y / 4.0 + mf.Z / A_metal;
    double mu_neutral = 1.0 / denom_neutral;
    
    /* Fully ionized mean molecular weight */
    /* mu_ionized = 1 / (2X + 3Y/4 + Z/2) */
    /* For metals: assume average A/Z ~ 2 (like O with A=16, Z=8) */
    double denom_ionized = 2.0 * mf.X + 0.75 * mf.Y + mf.Z / 2.0;
    double mu_ionized = 1.0 / denom_ionized;
    
    /* Smooth interpolation based on temperature */
    if (T <= T_ionize_low) {
        return mu_neutral;
    } else if (T >= T_ionize_high) {
        return mu_ionized;
    } else {
        /* Smooth transition using cosine interpolation */
        double f = (T - T_ionize_low) / (T_ionize_high - T_ionize_low);
        f = 0.5 * (1.0 - cos(M_PI * f));  /* Smooth S-curve */
        return mu_neutral * (1.0 - f) + mu_ionized * f;
    }
}

