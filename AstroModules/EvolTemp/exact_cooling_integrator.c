/*
 * ============================================================================
 * Exact Time Integration for Interstellar Gas Cooling/Heating
 * ============================================================================
 * 
 * Implementation based on:
 *   Zhu, Smith & Hernquist (2017), MNRAS 470, 1017-1025
 *   "Gas cooling in hydrodynamic simulations with an exact time integration scheme"
 *   https://doi.org/10.1093/mnras/stx1346
 *
 * Original method from:
 *   Townsend (2009), ApJS 181, 391
 *
 * Key Equations from the paper:
 *   Eq. (3):  u = kT / ((gamma-1) * mu * m_H)           [specific internal energy]
 *   Eq. (4):  Y(u) = (Lambda_ref/u_ref) * integral du/Lambda(u)  [temporal function]
 *   Eq. (5):  Lambda(u) = ((L2-L1)/(u2-u1))*(u-u1) + L1  [linear interpolation]
 *   Eq. (6):  dY = (Lambda_ref/u_ref) * A * ln((B+u2)/(B+u1))  if L2 != L1
 *   Eq. (7):  dY = (Lambda_ref/u_ref) * (u2-u1)/L1             if L2 == L1
 *   Eq. (8):  A = (u2-u1)/(L2-L1), B = (u2*L1-u1*L2)/(L2-L1)
 *   Eq. (9):  Y(u) = sum of dY                          [cumulative sum]
 *   Eq. (10): DeltaY = (u_i/Lambda_i) * (Lambda_ref/u_ref) * (dt/t_cool)
 *
 * This code reads cooling/heating rate tables from binary file generated by
 * cooling_rate_mpi.c (using CLOUDY) and integrates the cooling equation exactly.
 *
 * ============================================================================
 */

