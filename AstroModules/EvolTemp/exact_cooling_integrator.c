/* Get cooling time t_cool = u / |Lambda| */
double get_cooling_time(double nH, double Z, double T) {
    double Lambda = fabs(interp_net_rate(nH, Z, T));
    if (Lambda < EPSILON) return 1.0e30;
    
    /* Calculate gas mass density from nH using proper mass fractions */
    double rho = nH_to_rho(nH, Z);
    (void)rho;  /* Used when USE_GETMU is defined */
    
    double mu;
#ifdef USE_GETMU
    mu = get_mean_molecular_weight(rho, T, Z);
#else
//    mu = calc_mean_molecular_weight(T, Z);
    mu = calculate_mu(rho,T, Z);
#endif
    
    double u = T_to_u(T, mu);
    return u / Lambda;
}

/* Get net cooling rate at (nH, Z, T) */
double get_net_cooling_rate(double nH, double Z, double T) {
    return interp_net_rate(nH, Z, T);
}

