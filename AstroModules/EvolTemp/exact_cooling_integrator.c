/* ============================================================================
 * Eq. (6), (7), (8): Calculate deltaY for a segment
 *
 * For linear interpolation of Lambda(u) between (u1, L1) and (u2, L2):
 *   Eq. (5):  Lambda(u) = ((L2-L1)/(u2-u1))*(u-u1) + L1
 *
 * The integral delta_Y = (Lambda_ref/u_ref) * integral_{u1}^{u2} du/Lambda(u)
 *
 * If L1 != L2 (Eq. 6, 8):
 *   A = (u2-u1)/(L2-L1)
 *   B = (u2*L1 - u1*L2)/(L2-L1)
 *   delta_Y = (Lambda_ref/u_ref) * A * ln((B+u2)/(B+u1))
 *
 * If L1 == L2 (Eq. 7):
 *   delta_Y = (Lambda_ref/u_ref) * (u2-u1)/L1
 *
 * ============================================================================ */
static double calc_delta_Y(double u1, double u2, double L1, double L2,
                           double u_ref, double L_ref) {
    /* Eq. (6), (7), (8) */
    
    double du = u2 - u1;
    double dL = L2 - L1;
    
    /* Reference normalization factor: (Lambda_ref / u_ref) */
    double norm = L_ref / u_ref;
    
    /* Check if Lambda values are essentially equal */
    /* Eq. (7): delta_Y = (Lambda_ref/u_ref) * (u2-u1)/L1 */
    if (fabs(dL) < REL_TOLERANCE * fabs(L1 + L2) * 0.5 + EPSILON) {
        double L_avg = 0.5 * (L1 + L2);
        if (fabs(L_avg) < EPSILON) {
            /* Zero cooling rate - no change in Y */
            return 0.0;
        }
        return norm * du / L_avg;
    }
    
    /* Eq. (8): A = (u2-u1)/(L2-L1), B = (u2*L1 - u1*L2)/(L2-L1) */
    double A = du / dL;
    double B = (u2 * L1 - u1 * L2) / dL;
    
    /* Check for valid logarithm arguments */
    /* The argument (B + u) should be positive */
    double arg1 = B + u1;
    double arg2 = B + u2;
    
    if (arg1 * arg2 <= 0 || fabs(arg1) < EPSILON || fabs(arg2) < EPSILON) {
        /* Fallback to simple average */
        double L_avg = 0.5 * (L1 + L2);
        if (fabs(L_avg) < EPSILON) return 0.0;
        return norm * du / L_avg;
    }
    
    /* Eq. (6): delta_Y = (Lambda_ref/u_ref) * A * ln((B+u2)/(B+u1)) */
    double delta_Y = norm * A * log(arg2 / arg1);
    
    return delta_Y;
}

/* ============================================================================
 * Build Y function table for given (n_H, Z)
 *
 * Eq. (9): Y(u) = sum of delta_Y from u_ref to u
 *
 * We construct Y(T_k) for each temperature grid point.
 * Y increases monotonically for cooling (Lambda > 0).
 * Y decreases monotonically for heating (Lambda < 0).
 *
 * ============================================================================ */
static void build_Y_table_for_cell(int i, int j) {
    CoolingTable *ct = &g_table;
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    
    double nH = ct->density[i];
    double Z_metal = ct->metallicity[j];
    
    /* Calculate gas mass density from nH using proper mass fractions */
    double rho = nH_to_rho(nH, Z_metal);
    (void)rho;  /* May be used by get_mean_molecular_weight when USE_GETMU is defined */
    
    /* Choose reference point at middle temperature */
    int k_ref = N / 2;
    double T_ref = ct->temperature[k_ref];
    double L_ref = ct->net_rate[get_index(i, j, k_ref, L, M, N)];
    
    /* Avoid zero reference */
    if (fabs(L_ref) < EPSILON) {
        /* Find non-zero reference */
        for (int k = 0; k < N; k++) {
            double L_k = ct->net_rate[get_index(i, j, k, L, M, N)];
            if (fabs(L_k) > EPSILON) {
                k_ref = k;
                T_ref = ct->temperature[k_ref];
                L_ref = L_k;
                break;
            }
        }
    }
    if (fabs(L_ref) < EPSILON) L_ref = 1.0e-30;
    
    /* Get mu at reference point */
    double mu_ref;
#ifdef USE_GETMU
    mu_ref = get_mean_molecular_weight(rho, T_ref, Z_metal);
#else
//    mu_ref = calc_mean_molecular_weight(T_ref, Z_metal);
    mu_ref = calculate_mu(rho, T_ref, Z_metal);
#endif
    
    double u_ref = T_to_u(T_ref, mu_ref);
    
    /* Set Y = 0 at reference point */
    ct->Y_table[get_index(i, j, k_ref, L, M, N)] = 0.0;
    
    /* Eq. (9): Build Y by summing delta_Y from reference to higher T */
    double Y_accum = 0.0;
    for (int k = k_ref + 1; k < N; k++) {
        double T1 = ct->temperature[k - 1];
        double T2 = ct->temperature[k];
        double L1 = ct->net_rate[get_index(i, j, k - 1, L, M, N)];
        double L2 = ct->net_rate[get_index(i, j, k, L, M, N)];
        
        /* Get mu values */
        double mu1, mu2;
#ifdef USE_GETMU
        mu1 = get_mean_molecular_weight(rho, T1, Z_metal);
        mu2 = get_mean_molecular_weight(rho, T2, Z_metal);
#else
//        mu1 = calc_mean_molecular_weight(T1, Z_metal);
//       mu2 = calc_mean_molecular_weight(T2, Z_metal);
    	mu1 = calculate_mu(rho, T1, Z_metal);
    	mu2 = calculate_mu(rho, T2, Z_metal);
#endif
        
        double u1 = T_to_u(T1, mu1);
        double u2 = T_to_u(T2, mu2);
        
        /* Skip if either Lambda is near zero or changes sign */
        if (fabs(L1) < EPSILON || fabs(L2) < EPSILON || L1 * L2 < 0) {
            ct->Y_table[get_index(i, j, k, L, M, N)] = Y_accum;
            continue;
        }
        
        double dY = calc_delta_Y(u1, u2, L1, L2, u_ref, L_ref);
        Y_accum += dY;
        ct->Y_table[get_index(i, j, k, L, M, N)] = Y_accum;
    }
    
    /* Eq. (9): Build Y by summing delta_Y from reference to lower T */
    Y_accum = 0.0;
    for (int k = k_ref - 1; k >= 0; k--) {
        double T1 = ct->temperature[k + 1];
        double T2 = ct->temperature[k];
        double L1 = ct->net_rate[get_index(i, j, k + 1, L, M, N)];
        double L2 = ct->net_rate[get_index(i, j, k, L, M, N)];
        
        double mu1, mu2;
#ifdef USE_GETMU
        mu1 = get_mean_molecular_weight(rho, T1, Z_metal);
        mu2 = get_mean_molecular_weight(rho, T2, Z_metal);
#else
//        mu1 = calc_mean_molecular_weight(T1, Z_metal);
//        mu2 = calc_mean_molecular_weight(T2, Z_metal);
        mu1 = calculate_mu(rho,T1, Z_metal);
        mu2 = calculate_mu(rho,T2, Z_metal);
#endif
        
        double u1 = T_to_u(T1, mu1);
        double u2 = T_to_u(T2, mu2);
        
        if (fabs(L1) < EPSILON || fabs(L2) < EPSILON || L1 * L2 < 0) {
            ct->Y_table[get_index(i, j, k, L, M, N)] = Y_accum;
            continue;
        }
        
        double dY = calc_delta_Y(u1, u2, L1, L2, u_ref, L_ref);
        Y_accum += dY;
        ct->Y_table[get_index(i, j, k, L, M, N)] = Y_accum;
    }
}

/* ============================================================================
 * Load Cooling Table from Binary File
 * 
 * Binary file format (from cooling_rate_mpi.c):
 *   1. GridParams structure
 *   2. cooling_grid[L * M * N] doubles
 *   3. heating_grid[L * M * N] doubles
 *
 * ============================================================================ */
int load_cooling_table(const char *filename) {
    CoolingTable *ct = &g_table;
    
    /* Free previous data if any */
    if (ct->loaded) {
        free(ct->density);
        free(ct->metallicity);
        free(ct->temperature);
        free(ct->cooling_rate);
        free(ct->heating_rate);
        free(ct->net_rate);
        free(ct->Y_table);
        ct->loaded = 0;
    }
    
    FILE *fp = fopen(filename, "rb");
    if (!fp) {
        fprintf(stderr, "Error: Cannot open file '%s'\n", filename);
        return -1;
    }
    
    /* Read grid parameters */
    if (fread(&ct->params, sizeof(GridParams), 1, fp) != 1) {
        fprintf(stderr, "Error: Failed to read grid parameters\n");
        fclose(fp);
        return -1;
    }
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    size_t total_size = (size_t)L * M * N;
    
    printf("Loading cooling table: %s\n", filename);
    printf("  Grid dimensions: L=%d (density), M=%d (metallicity), N=%d (temperature)\n", L, M, N);
    printf("  redshift %f\n", ct->params.redshift);
    printf("  Density range: [%.2e, %.2e] cm^-3\n", ct->params.density_min, ct->params.density_max);
    printf("  Metallicity range: [%.2e, %.2e] Z_solar\n", ct->params.metallicity_min, ct->params.metallicity_max);
    printf("  Temperature range: [%.2e, %.2e] K\n", ct->params.temp_min, ct->params.temp_max);
    
    /* Allocate memory */
    ct->density = (double*)malloc(L * sizeof(double));
    ct->metallicity = (double*)malloc(M * sizeof(double));
    ct->temperature = (double*)malloc(N * sizeof(double));
    ct->cooling_rate = (double*)malloc(total_size * sizeof(double));
    ct->heating_rate = (double*)malloc(total_size * sizeof(double));
    ct->net_rate = (double*)malloc(total_size * sizeof(double));
    ct->Y_table = (double*)malloc(total_size * sizeof(double));
    
    if (!ct->density || !ct->metallicity || !ct->temperature ||
        !ct->cooling_rate || !ct->heating_rate || !ct->net_rate || !ct->Y_table) {
        fprintf(stderr, "Error: Memory allocation failed\n");
        fclose(fp);
        return -1;
    }
    
    /* Build density grid (log-spaced) */
    double log_dens_min = log10(ct->params.density_min);
    double log_dens_max = log10(ct->params.density_max);
    double dens_step = (log_dens_max - log_dens_min) / (L - 1);
    for (int i = 0; i < L; i++) {
        ct->density[i] = pow(10.0, log_dens_min + i * dens_step);
    }
    
    /* Build metallicity grid (log-spaced) */
    double log_metal_min = log10(ct->params.metallicity_min);
    double log_metal_max = log10(ct->params.metallicity_max);
    double metal_step = (log_metal_max - log_metal_min) / (M - 1);
    for (int j = 0; j < M; j++) {
        ct->metallicity[j] = pow(10.0, log_metal_min + j * metal_step);
    }
    
    /* Copy temperature grid from params */
    for (int k = 0; k < N; k++) {
        ct->temperature[k] = ct->params.temp[k];
    }
    
    /* Read cooling rates */
    if (fread(ct->cooling_rate, sizeof(double), total_size, fp) != total_size) {
        fprintf(stderr, "Error: Failed to read cooling rates\n");
        fclose(fp);
        return -1;
    }
    
    /* Read heating rates */
    if (fread(ct->heating_rate, sizeof(double), total_size, fp) != total_size) {
        fprintf(stderr, "Error: Failed to read heating rates\n");
        fclose(fp);
        return -1;
    }
    
    fclose(fp);
    
    /* ========================================================================
     * CRITICAL: Unit Conversion
     * ========================================================================
     * CLOUDY outputs cooling/heating rates in erg/cm^3/s (volumetric).
     * The exact integration method requires erg/g/s (specific).
     * 
     * Conversion: Lambda_specific = Lambda_volumetric / rho
     * where rho = nH * m_H / X_H
     * 
     * We do this conversion here for each (density, metallicity, temperature)
     * point in the table.
     * ======================================================================== */
    printf("  Converting units: erg/cm^3/s -> erg/g/s...\n");
    
    for (int i = 0; i < L; i++) {
        double nH = ct->density[i];
        
        for (int j = 0; j < M; j++) {
            double Z_metal = ct->metallicity[j];
            
            /* Calculate gas mass density from hydrogen number density */
            double rho = nH_to_rho(nH, Z_metal);
            
            for (int k = 0; k < N; k++) {
                int idx = get_index(i, j, k, L, M, N);
                
                /* Convert from erg/cm^3/s to erg/g/s */
                ct->cooling_rate[idx] /= rho;
                ct->heating_rate[idx] /= rho;
            }
        }
    }
    
    /* Compute net cooling rate = cooling - heating */
    /* Positive net_rate means cooling (du/dt < 0), Negative means heating (du/dt > 0) */
    for (size_t idx = 0; idx < total_size; idx++) {
        ct->net_rate[idx] = ct->cooling_rate[idx] - ct->heating_rate[idx];
    }
    
    /* Build Y table for each (density, metallicity) cell */
    printf("  Building Y-function tables (Eq. 9)...\n");
    for (int i = 0; i < L; i++) {
        for (int j = 0; j < M; j++) {
            build_Y_table_for_cell(i, j);
        }
    }
    
    ct->loaded = 1;
    printf("  Cooling table loaded successfully.\n\n");
    
    return 0;
}

/* Free cooling table memory */
void free_cooling_table(void) {
    CoolingTable *ct = &g_table;
    if (ct->loaded) {
        free(ct->density);
        free(ct->metallicity);
        free(ct->temperature);
        free(ct->cooling_rate);
        free(ct->heating_rate);
        free(ct->net_rate);
        free(ct->Y_table);
        if (ct->log_T_final_table) {
            free(ct->log_T_final_table);
        }
        memset(ct, 0, sizeof(CoolingTable));
    }
}

/* ============================================================================
 * Helper function for bilinear Y interpolation (thread-safe)
 * ============================================================================ */
static inline double interp_Y_bilinear(const CoolingTable *ct, 
                                        int i, int j, int k,
                                        int L, int M, int N,
                                        double f_n, double f_z) {
    double Y00 = ct->Y_table[get_index(i,   j,   k, L, M, N)];
    double Y01 = ct->Y_table[get_index(i,   j+1, k, L, M, N)];
    double Y10 = ct->Y_table[get_index(i+1, j,   k, L, M, N)];
    double Y11 = ct->Y_table[get_index(i+1, j+1, k, L, M, N)];
    double Y0 = lerp(Y00, Y01, f_z);
    double Y1 = lerp(Y10, Y11, f_z);
    return lerp(Y0, Y1, f_n);
}

/* ============================================================================
 * Exact Time Integration (Main Algorithm)
 *
 * Based on Zhu et al. (2017), MNRAS 470, 1017 - Equations (4)-(10)
 *
 * The key idea:
 *   1. Transform the cooling equation du/dt = -Lambda(u) to dY/dt = const
 *      where Y(u) = (Lambda_ref/u_ref) * integral du/Lambda(u)  [Eq. 4]
 *   
 *   2. Advance Y by Delta_Y over timestep dt:
 *      Eq. (10): Delta_Y = (u_i/Lambda_i) * (Lambda_ref/u_ref) * (dt/t_cool)
 *      where t_cool = u/|Lambda| is the cooling time
 *      So: Delta_Y = (Lambda_ref/u_ref) * dt
 *
 *   3. Find new u (and T) by inverting Y(u_new) = Y(u_old) + Delta_Y
 *
 * ============================================================================ */
double exact_integrate(double nH, double Z, double T_init, double dt, double *T_final) {
    CoolingTable *ct = &g_table;
    
    if (!ct->loaded) {
        fprintf(stderr, "Error: Cooling table not loaded!\n");
        *T_final = T_init;
        return 0.0;
    }
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    
    /* Clamp input values to table range */
    nH = clamp(nH, ct->density[0], ct->density[L-1]);
    Z = clamp(Z, ct->metallicity[0], ct->metallicity[M-1]);
    T_init = clamp(T_init, ct->temperature[0], ct->temperature[N-1]);
    
    /* Get initial net cooling rate */
    double Lambda_init = interp_net_rate(nH, Z, T_init);
    
    /* Check if cooling/heating is negligible */
    if (fabs(Lambda_init) < EPSILON) {
        *T_final = T_init;
        return 0.0;
    }
    
    /* Determine direction: cooling (Lambda > 0) or heating (Lambda < 0) */
    int cooling = (Lambda_init > 0);
    
    /* Calculate gas mass density from nH using proper mass fractions */
    double rho = nH_to_rho(nH, Z);
    
    /* Get mean molecular weight */
    double mu_init;
#ifdef USE_GETMU
    mu_init = get_mean_molecular_weight(rho, T_init, Z);
#else
//    mu_init = calc_mean_molecular_weight(T_init, Z);
    mu_init = calculate_mu(rho,T_init, Z);
#endif
    
    /* Calculate initial internal energy (for reference, Eq. 3) */
    /* double u_init = T_to_u(T_init, mu_init); */
    (void)mu_init;  /* Used for documentation, may be used in future */
    (void)rho;      /* Used when USE_GETMU is defined */
    
    /* Find reference values at this (nH, Z) */
    int i = find_index_log(ct->density, L, nH);
    int j = find_index_log(ct->metallicity, M, Z);
    int k_ref = N / 2;
    
    double T_ref = ct->temperature[k_ref];
    double L_ref = ct->net_rate[get_index(i, j, k_ref, L, M, N)];
    if (fabs(L_ref) < EPSILON) L_ref = fabs(Lambda_init);
    
    double mu_ref;
#ifdef USE_GETMU
    mu_ref = get_mean_molecular_weight(rho, T_ref, Z);
#else
//    mu_ref = calc_mean_molecular_weight(T_ref, Z);
    mu_ref = calculate_mu(rho, T_ref, Z);
#endif
    double u_ref = T_to_u(T_ref, mu_ref);
    
    /* Eq. (10): Calculate Delta_Y for this timestep
     * 
     * The equation in the paper:
     *   Delta_Y = (u_i / Lambda_i) * (Lambda_ref / u_ref) * (dt / t_cool)
     * 
     * where t_cool = u / |Lambda|
     * 
     * Simplifying:
     *   Delta_Y = (u_i / Lambda_i) * (Lambda_ref / u_ref) * (dt * |Lambda| / u)
     *           = (Lambda_ref / u_ref) * dt * sign(Lambda)
     * 
     * For cooling (Lambda > 0): Y increases (moves to lower T)
     * For heating (Lambda < 0): Y decreases (moves to higher T)
     */
    double Delta_Y = (fabs(L_ref) / u_ref) * dt;
    
    /* Find current temperature index */
    int k_init = find_index(ct->temperature, N, T_init);
    
    /* Get interpolation weights for density and metallicity */
    double f_n = (safe_log10(nH) - safe_log10(ct->density[i])) / 
                 (safe_log10(ct->density[i+1]) - safe_log10(ct->density[i]) + 1e-30);
    double f_z = (safe_log10(Z) - safe_log10(ct->metallicity[j])) / 
                 (safe_log10(ct->metallicity[j+1]) - safe_log10(ct->metallicity[j]) + 1e-30);
    f_n = clamp(f_n, 0.0, 1.0);
    f_z = clamp(f_z, 0.0, 1.0);
    
    /* Interpolate Y at initial T (between grid points) */
    double f_t = (safe_log10(T_init) - safe_log10(ct->temperature[k_init])) / 
                 (safe_log10(ct->temperature[k_init+1]) - safe_log10(ct->temperature[k_init]) + 1e-30);
    f_t = clamp(f_t, 0.0, 1.0);
    
    double Y_init = lerp(interp_Y_bilinear(ct, i, j, k_init, L, M, N, f_n, f_z), interp_Y_bilinear(ct, i, j, k_init+1, L, M, N, f_n, f_z), f_t);
    
    /* Target Y after timestep
     * 
     * From Eq. (4): Y(u) = (#_ref/u_ref) * # du/#(u)
     * 
     * dY/dt = (#_ref/u_ref) * (du/dt)/# = (#_ref/u_ref) * (-#)/# = -#_ref/u_ref
     * 
     * So for constant dt:
     *   Delta_Y = |dY/dt| * dt = (#_ref/u_ref) * dt  (always positive)
     * 
     * But the actual change in Y is:
     *   Cooling (# > 0): T decreases # u decreases # Y decreases
     *   Heating (# < 0): T increases # u increases # Y increases
     */
    double Y_target;
    if (cooling) {
        /* Cooling: Y decreases as T decreases */
        Y_target = Y_init - Delta_Y;
    } else {
        /* Heating: Y increases as T increases */
        Y_target = Y_init + Delta_Y;
    }
    
    /* Eq. (9): Find temperature where Y(T) = Y_target by searching the table */
    /* Walk through temperature grid to find the segment containing Y_target */
    
    double T_new = T_init;
    int found = 0;
    
    if (cooling) {
        /* Cooling: Y decreases as T decreases (energy loss)
         * Search from current position toward lower temperatures
         * 
         * IMPORTANT: First check if Y_target is still within the initial segment
         * (between k_init and k_init+1) before searching downward
         */
        
        /* First, check the current segment [k_init, k_init+1] */
        if (k_init < N - 1) {
            double Y_lo = interp_Y_bilinear(ct, i, j, k_init, L, M, N, f_n, f_z);
            double Y_hi = interp_Y_bilinear(ct, i, j, k_init + 1, L, M, N, f_n, f_z);
            
            /* Y increases with T (higher k = higher T = higher Y for cooling regime) */
            if (Y_target >= Y_lo && Y_target <= Y_hi) {
                /* Target is in initial segment - interpolate */
                double frac = 0.0;
                if (fabs(Y_hi - Y_lo) > EPSILON) {
                    frac = (Y_target - Y_lo) / (Y_hi - Y_lo);
                }
                frac = clamp(frac, 0.0, 1.0);
                
                double log_T_lo = safe_log10(ct->temperature[k_init]);
                double log_T_hi = safe_log10(ct->temperature[k_init + 1]);
                T_new = pow(10.0, lerp(log_T_lo, log_T_hi, frac));
                found = 1;
            }
        }
        
        /* If not found in initial segment, search downward toward lower T */
        for (int k = k_init; k >= 0 && !found; k--) {
            /* Check for equilibrium crossing (Lambda sign change) */
            double Lambda_k = ct->net_rate[get_index(i, j, k, L, M, N)];
            if (Lambda_k <= 0) {
                /* Crossed into heating regime - find equilibrium temperature */
                if (k < k_init) {
                    double Lambda_prev = ct->net_rate[get_index(i, j, k+1, L, M, N)];
                    if (fabs(Lambda_prev - Lambda_k) > EPSILON) {
                        double frac = Lambda_prev / (Lambda_prev - Lambda_k);
                        frac = clamp(frac, 0.0, 1.0);
                        double log_T_k = safe_log10(ct->temperature[k]);
                        double log_T_prev = safe_log10(ct->temperature[k+1]);
                        T_new = pow(10.0, lerp(log_T_prev, log_T_k, frac));
                    } else {
                        T_new = ct->temperature[k+1];
                    }
                } else {
                    T_new = ct->temperature[k];
                }
                found = 1;
                break;
            }
            
            /* Check if Y_target is in segment [k-1, k] */
            if (k > 0) {
                double Y_k = interp_Y_bilinear(ct, i, j, k, L, M, N, f_n, f_z);
                double Y_km1 = interp_Y_bilinear(ct, i, j, k - 1, L, M, N, f_n, f_z);
                
                /* For cooling going down: Y[k] > Y[k-1] typically */
                double Y_lo = (Y_km1 < Y_k) ? Y_km1 : Y_k;
                double Y_hi = (Y_km1 < Y_k) ? Y_k : Y_km1;
                
                if (Y_target >= Y_lo && Y_target <= Y_hi) {
                    double frac = 0.0;
                    if (fabs(Y_k - Y_km1) > EPSILON) {
                        frac = (Y_target - Y_k) / (Y_km1 - Y_k);
                    }
                    frac = clamp(frac, 0.0, 1.0);
                    
                    double log_T_k = safe_log10(ct->temperature[k]);
                    double log_T_km1 = safe_log10(ct->temperature[k - 1]);
                    T_new = pow(10.0, lerp(log_T_k, log_T_km1, frac));
                    found = 1;
                }
            }
        }
        
        if (!found) {
            /* Reached minimum temperature */
            T_new = ct->temperature[0];
        }
    } else {
        /* Heating: search toward higher temperatures */
        for (int k = k_init; k < N - 1 && !found; k++) {
            double Y_k = interp_Y_bilinear(ct, i, j, k, L, M, N, f_n, f_z);
            double Y_k1 = interp_Y_bilinear(ct, i, j, k+1, L, M, N, f_n, f_z);
            
            /* Check if target is in this segment */
            if ((Y_target >= Y_k && Y_target <= Y_k1) || 
                (Y_target <= Y_k && Y_target >= Y_k1)) {
                /* Interpolate within segment */
                double frac = 0.0;
                if (fabs(Y_k1 - Y_k) > EPSILON) {
                    frac = (Y_target - Y_k) / (Y_k1 - Y_k);
                }
                frac = clamp(frac, 0.0, 1.0);
                
                double log_T_k = safe_log10(ct->temperature[k]);
                double log_T_k1 = safe_log10(ct->temperature[k+1]);
                T_new = pow(10.0, lerp(log_T_k, log_T_k1, frac));
                found = 1;
            }
            
            /* Check for sign change in net rate (equilibrium crossing) */
            double Lambda_k = ct->net_rate[get_index(i, j, k, L, M, N)];
            if (Lambda_k >= 0 && k < N - 1) {
                /* Crossed into cooling regime - stop at equilibrium */
                T_new = ct->temperature[k];
                found = 1;
            }
        }
        
        if (!found) {
            /* Reached maximum temperature */
            T_new = ct->temperature[N-1];
        }
    }
    
    /* Clamp final temperature to table bounds */
    T_new = clamp(T_new, ct->temperature[0], ct->temperature[N-1]);
    
    
    *T_final = T_new;
    return T_new - T_init;
}

/* ============================================================================
 * Build Lookup Table for Fast Interpolation
 *
 * This function pre-computes log10(T_final/T_init) for each grid point
 * (density[i], metallicity[j], temperature[k]) using exact_integrate().
 *
 * Storing log10(T_final/T_init) (the fractional change) provides the best
 * interpolation accuracy because:
 *   1. The ratio varies smoothly even across large temperature ranges
 *   2. Near equilibrium, the ratio is ~1 (log ~ 0), which interpolates well
 *   3. Handles both cooling (ratio < 1) and heating (ratio > 1) uniformly
 *
 * Parameters:
 *   dt - The fixed timestep [seconds] for which to build the table
 *
 * Returns:
 *   0 on success, -1 on failure
 *
 * ============================================================================ */
int build_dT_lookup_table(double dt) {
    CoolingTable *ct = &g_table;
    
    if (!ct->loaded) {
        fprintf(stderr, "Error: Cooling table must be loaded before building lookup table!\n");
        return -1;
    }
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    size_t total_size = (size_t)L * M * N;
    
    printf("Building T_ratio lookup table (log-space)...\n");
    printf("  Grid: L=%d, M=%d, N=%d (total %zu entries)\n", L, M, N, total_size);
    printf("  Timestep dt = %.6e s (%.4f Myr)\n", dt, dt / MYR_IN_SEC);
    
    /* Allocate memory for lookup table if not already allocated */
    if (ct->log_T_final_table == NULL) {
        ct->log_T_final_table = (double*)malloc(total_size * sizeof(double));
        if (!ct->log_T_final_table) {
            fprintf(stderr, "Error: Failed to allocate memory for lookup table\n");
            return -1;
        }
    }
    
    /* Store the timestep used */
    ct->dT_table_dt = dt;
    
    /* Pre-compute log10(T_final/T_init) for each grid point */
    int progress_step = L / 10;
    if (progress_step < 1) progress_step = 1;
#ifdef _OPENMP
    int id;
#pragma omp parallel for schedule(dynamic)
    for(id=0;id<L*M*N;id++){
        int i = id / (M *N);
        int j = (id/ N) % M;
        int k = id % N;
        double nH = ct->density[i];
        double Z = ct->metallicity[j];
        double T_init = ct->temperature[k];
        double T_final;
        exact_integrate(nH, Z, T_init, dt, &T_final);
        int idx = get_index(i, j, k, L, M, N);
        ct->log_T_final_table[idx] = safe_log10(T_final) - safe_log10(T_init);
    }
#else
    for (int i = 0; i < L; i++) {
        double nH = ct->density[i];
        
        if (i % progress_step == 0) {
            printf("  Progress: %d%% (density index %d/%d)\n", 
                   (int)(100.0 * i / L), i, L);
        }
        
        for (int j = 0; j < M; j++) {
            double Z = ct->metallicity[j];
            
            for (int k = 0; k < N; k++) {
                double T_init = ct->temperature[k];
                double T_final;
                
                /* Use exact_integrate to compute T_final at this grid point */
                exact_integrate(nH, Z, T_init, dt, &T_final);
                
                /* Store log10(T_final/T_init) in lookup table */
                /* This is the log of the temperature ratio */
                int idx = get_index(i, j, k, L, M, N);
                ct->log_T_final_table[idx] = safe_log10(T_final) - safe_log10(T_init);
            }
        }
    }
#endif
    
    ct->dT_table_loaded = 1;
    printf("  Lookup table built successfully.\n\n");
    
    return 0;
}

/* ============================================================================
 * Free Lookup Table
 *
 * Releases memory used by the lookup table without freeing the entire
 * cooling table.
 * ============================================================================ */
void free_dT_lookup_table(void) {
    CoolingTable *ct = &g_table;
    if (ct->log_T_final_table) {
        free(ct->log_T_final_table);
        ct->log_T_final_table = NULL;
        ct->dT_table_dt = 0.0;
        ct->dT_table_loaded = 0;
        printf("Lookup table freed.\n");
    }
}

/* ============================================================================
 * Fast Exact Integration via Lookup Table Interpolation
 *
 * This function performs the same calculation as exact_integrate() but uses
 * a pre-computed lookup table with trilinear interpolation for speed.
 *
 * The lookup table stores log10(T_final/T_init) at each grid point.
 * Interpolation is performed in log-space:
 *   1. Trilinear interpolation of log10(T_final/T_init)
 *   2. Convert: T_final = T_init * 10^(interpolated value)
 *   3. Calculate dT = T_final - T_init
 *
 * This approach provides the best accuracy because the temperature ratio
 * varies smoothly across all regimes (cooling, heating, equilibrium).
 *
 * Parameters:
 *   nH      - Hydrogen number density [cm^-3]
 *   Z       - Metallicity [Z_solar]
 *   T_init  - Initial temperature [K]
 *   T_final - Output: final temperature after cooling/heating [K]
 *
 * Returns:
 *   dT = T_final - T_init (temperature change)
 *
 * Note: If the lookup table was built with timestep dt, this function
 *       effectively integrates over that same timestep.
 *
 * ============================================================================ */
double interpolate_exact_integrate(double nH, double Z, double T_init, double *T_final) {
    CoolingTable *ct = &g_table;
    
    /* Check if tables are loaded */
    if (!ct->loaded) {
        fprintf(stderr, "Error: Cooling table not loaded!\n");
        *T_final = T_init;
        return 0.0;
    }
    
    if (!ct->dT_table_loaded || ct->log_T_final_table == NULL) {
        fprintf(stderr, "Error: Lookup table not built! Call build_dT_lookup_table(dt) first.\n");
        *T_final = T_init;
        return 0.0;
    }
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    
    /* Clamp input values to table range */
    double nH_clamped = clamp(nH, ct->density[0], ct->density[L-1]);
    double Z_clamped = clamp(Z, ct->metallicity[0], ct->metallicity[M-1]);
    double T_clamped = clamp(T_init, ct->temperature[0], ct->temperature[N-1]);
    
    /* Find indices for density (log-spaced) */
    int i = find_index_log(ct->density, L, nH_clamped);
    double f_n;
    if (ct->density[i+1] > ct->density[i]) {
        f_n = (safe_log10(nH_clamped) - safe_log10(ct->density[i])) / 
              (safe_log10(ct->density[i+1]) - safe_log10(ct->density[i]));
    } else {
        f_n = 0.0;
    }
    f_n = clamp(f_n, 0.0, 1.0);
    
    /* Find indices for metallicity (log-spaced) */
    int j = find_index_log(ct->metallicity, M, Z_clamped);
    double f_z;
    if (ct->metallicity[j+1] > ct->metallicity[j]) {
        f_z = (safe_log10(Z_clamped) - safe_log10(ct->metallicity[j])) / 
              (safe_log10(ct->metallicity[j+1]) - safe_log10(ct->metallicity[j]));
    } else {
        f_z = 0.0;
    }
    f_z = clamp(f_z, 0.0, 1.0);
    
    /* Find indices for temperature (log-spaced interpolation) */
    int k = find_index(ct->temperature, N, T_clamped);
    double f_t;
    if (ct->temperature[k+1] > ct->temperature[k]) {
        f_t = (safe_log10(T_clamped) - safe_log10(ct->temperature[k])) / 
              (safe_log10(ct->temperature[k+1]) - safe_log10(ct->temperature[k]));
    } else {
        f_t = 0.0;
    }
    f_t = clamp(f_t, 0.0, 1.0);
    
    /* Trilinear interpolation of log10(T_final/T_init) from the lookup table */
    /* Get the 8 corner values of the interpolation cube */
    double logR000 = ct->log_T_final_table[get_index(i,   j,   k,   L, M, N)];
    double logR001 = ct->log_T_final_table[get_index(i,   j,   k+1, L, M, N)];
    double logR010 = ct->log_T_final_table[get_index(i,   j+1, k,   L, M, N)];
    double logR011 = ct->log_T_final_table[get_index(i,   j+1, k+1, L, M, N)];
    double logR100 = ct->log_T_final_table[get_index(i+1, j,   k,   L, M, N)];
    double logR101 = ct->log_T_final_table[get_index(i+1, j,   k+1, L, M, N)];
    double logR110 = ct->log_T_final_table[get_index(i+1, j+1, k,   L, M, N)];
    double logR111 = ct->log_T_final_table[get_index(i+1, j+1, k+1, L, M, N)];
    
    /* Interpolate along temperature axis */
    double logR00 = lerp(logR000, logR001, f_t);
    double logR01 = lerp(logR010, logR011, f_t);
    double logR10 = lerp(logR100, logR101, f_t);
    double logR11 = lerp(logR110, logR111, f_t);
    
    /* Interpolate along metallicity axis */
    double logR0 = lerp(logR00, logR01, f_z);
    double logR1 = lerp(logR10, logR11, f_z);
    
    /* Interpolate along density axis */
    double logR_interp = lerp(logR0, logR1, f_n);
    
    /* Convert back: T_final = T_init * 10^(log_ratio) */
    double T_new = T_init * pow(10.0, logR_interp);
    
    /* Clamp to valid temperature range */
    T_new = clamp(T_new, ct->temperature[0], ct->temperature[N-1]);
    
    *T_final = T_new;
    return T_new - T_init;
}

