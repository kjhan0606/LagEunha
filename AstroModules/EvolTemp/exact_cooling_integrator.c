/* ============================================================================
 * Helper Functions
 * ============================================================================ */

/* Clamp value between min and max */
static double clamp(double x, double a, double b) {
    return (x < a) ? a : ((x > b) ? b : x);
}

/* Safe log10 that handles zero/negative values */
static double safe_log10(double x) {
    return (x > 0) ? log10(x) : -30.0;
}

/* Linear interpolation */
static double lerp(double x0, double x1, double f) {
    return x0 + f * (x1 - x0);
}

/* Find index in sorted array (log-spaced) */
static int find_index_log(const double *arr, int n, double val) {
    if (val <= arr[0]) return 0;
    if (val >= arr[n-1]) return n - 2;
    
    double log_val = safe_log10(val);
    double log_min = safe_log10(arr[0]);
    double log_max = safe_log10(arr[n-1]);
    double step = (log_max - log_min) / (n - 1);
    
    int idx = (int)((log_val - log_min) / step);
    idx = (idx < 0) ? 0 : ((idx >= n - 1) ? n - 2 : idx);
    
    /* Fine-tune the index */
    while (idx > 0 && arr[idx] > val) idx--;
    while (idx < n - 2 && arr[idx + 1] < val) idx++;
    
    return idx;
}

/* Find index in array (possibly non-uniform spacing) */
static int find_index(const double *arr, int n, double val) {
    if (val <= arr[0]) return 0;
    if (val >= arr[n-1]) return n - 2;
    
    /* Binary search */
    int lo = 0, hi = n - 1;
    while (hi - lo > 1) {
        int mid = (lo + hi) / 2;
        if (arr[mid] > val)
            hi = mid;
        else
            lo = mid;
    }
    return lo;
}

/* ============================================================================
 * Eq. (3): Thermodynamic Conversions
 *          u = kT / ((gamma-1) * mu * m_H)
 * ============================================================================ */

/* Convert temperature to specific internal energy */
/* Eq. (3): T -> u */
static double T_to_u(double T, double mu) {
    return K_BOLTZMANN * T / ((GAMMA - 1.0) * mu * M_PROTON);
}

/* Convert specific internal energy to temperature */
/* Inverse of Eq. (3): u -> T */
static double u_to_T(double u, double mu) {
    return u * (GAMMA - 1.0) * mu * M_PROTON / K_BOLTZMANN;
}

/* ============================================================================
 * Table Index Calculation
 * ============================================================================ */

/* Get flat array index from (i_dens, j_metal, k_temp) */
static inline int get_index(int i, int j, int k, int L, int M, int N) {
    /* Storage order: [density][metallicity][temperature] */
    /* From cooling_rate_mpi.c: id = i * M + j, then cooling_grid[id * N + k] */
    return (i * M + j) * N + k;
}

/* ============================================================================
 * Trilinear Interpolation
 * ============================================================================ */

/* Interpolate net cooling rate Lambda(n_H, Z, T) */
/* Positive = cooling (energy loss), Negative = heating (energy gain) */
static double interp_net_rate(double nH, double Z, double T) {
    CoolingTable *ct = &g_table;
    
    if (!ct->loaded) {
        fprintf(stderr, "Error: Cooling table not loaded!\n");
        return 0.0;
    }
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    
    /* Find indices and fractions for density */
    int i = find_index_log(ct->density, L, nH);
    double f_n;
    if (ct->density[i+1] > ct->density[i]) {
        f_n = (safe_log10(nH) - safe_log10(ct->density[i])) / 
              (safe_log10(ct->density[i+1]) - safe_log10(ct->density[i]));
    } else {
        f_n = 0.0;
    }
    f_n = clamp(f_n, 0.0, 1.0);
    
    /* Find indices and fractions for metallicity */
    int j = find_index_log(ct->metallicity, M, Z);
    double f_z;
    if (ct->metallicity[j+1] > ct->metallicity[j]) {
        f_z = (safe_log10(Z) - safe_log10(ct->metallicity[j])) / 
              (safe_log10(ct->metallicity[j+1]) - safe_log10(ct->metallicity[j]));
    } else {
        f_z = 0.0;
    }
    f_z = clamp(f_z, 0.0, 1.0);
    
    /* Find indices and fractions for temperature */
    int k = find_index(ct->temperature, N, T);
    double f_t;
    if (ct->temperature[k+1] > ct->temperature[k]) {
        f_t = (safe_log10(T) - safe_log10(ct->temperature[k])) / 
              (safe_log10(ct->temperature[k+1]) - safe_log10(ct->temperature[k]));
    } else {
        f_t = 0.0;
    }
    f_t = clamp(f_t, 0.0, 1.0);
    
    /* Trilinear interpolation */
    double c000 = ct->net_rate[get_index(i,   j,   k,   L, M, N)];
    double c001 = ct->net_rate[get_index(i,   j,   k+1, L, M, N)];
    double c010 = ct->net_rate[get_index(i,   j+1, k,   L, M, N)];
    double c011 = ct->net_rate[get_index(i,   j+1, k+1, L, M, N)];
    double c100 = ct->net_rate[get_index(i+1, j,   k,   L, M, N)];
    double c101 = ct->net_rate[get_index(i+1, j,   k+1, L, M, N)];
    double c110 = ct->net_rate[get_index(i+1, j+1, k,   L, M, N)];
    double c111 = ct->net_rate[get_index(i+1, j+1, k+1, L, M, N)];
    
    double c00 = lerp(c000, c001, f_t);
    double c01 = lerp(c010, c011, f_t);
    double c10 = lerp(c100, c101, f_t);
    double c11 = lerp(c110, c111, f_t);
    
    double c0 = lerp(c00, c01, f_z);
    double c1 = lerp(c10, c11, f_z);
    
    return lerp(c0, c1, f_n);
}

/* Interpolate cooling rate only */
static double interp_cooling_rate(double nH, double Z, double T) {
    CoolingTable *ct = &g_table;
    
    if (!ct->loaded) return 0.0;
    
    int L = ct->params.L;
    int M = ct->params.M;
    int N = ct->params.N;
    
    int i = find_index_log(ct->density, L, nH);
    int j = find_index_log(ct->metallicity, M, Z);
    int k = find_index(ct->temperature, N, T);
    
    double f_n = (safe_log10(nH) - safe_log10(ct->density[i])) / 
                 (safe_log10(ct->density[i+1]) - safe_log10(ct->density[i]) + 1e-30);
    double f_z = (safe_log10(Z) - safe_log10(ct->metallicity[j])) / 
                 (safe_log10(ct->metallicity[j+1]) - safe_log10(ct->metallicity[j]) + 1e-30);
    double f_t = (safe_log10(T) - safe_log10(ct->temperature[k])) / 
                 (safe_log10(ct->temperature[k+1]) - safe_log10(ct->temperature[k]) + 1e-30);
    
    f_n = clamp(f_n, 0.0, 1.0);
    f_z = clamp(f_z, 0.0, 1.0);
    f_t = clamp(f_t, 0.0, 1.0);
    
    double c000 = ct->cooling_rate[get_index(i,   j,   k,   L, M, N)];
    double c001 = ct->cooling_rate[get_index(i,   j,   k+1, L, M, N)];
    double c010 = ct->cooling_rate[get_index(i,   j+1, k,   L, M, N)];
    double c011 = ct->cooling_rate[get_index(i,   j+1, k+1, L, M, N)];
    double c100 = ct->cooling_rate[get_index(i+1, j,   k,   L, M, N)];
    double c101 = ct->cooling_rate[get_index(i+1, j,   k+1, L, M, N)];
    double c110 = ct->cooling_rate[get_index(i+1, j+1, k,   L, M, N)];
    double c111 = ct->cooling_rate[get_index(i+1, j+1, k+1, L, M, N)];
    
    double c00 = lerp(c000, c001, f_t);
    double c01 = lerp(c010, c011, f_t);
    double c10 = lerp(c100, c101, f_t);
    double c11 = lerp(c110, c111, f_t);
    
    double c0 = lerp(c00, c01, f_z);
    double c1 = lerp(c10, c11, f_z);
    
    return lerp(c0, c1, f_n);
}

