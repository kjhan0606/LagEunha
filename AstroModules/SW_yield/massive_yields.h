/**
 * @file stellar_wind_yields.h
 * @brief Massive star stellar wind yields from Limongi & Chieffi (2018)
 * 
 * Source: Limongi, M. & Chieffi, A. 2018, ApJS, 237, 13
 * 
 * These are WIND-ONLY yields (ejected before supernova explosion).
 * Yields are rotation-weighted: v=0 (40%), v=150 (45%), v=300 (15%) km/s
 * 
 * Yield definition: yield_i = M_ejected,i - X_i,0 * M_ejected,total
 * 
 * IMPORTANT: Z_total is defined as Z_total = -(H + He) to ensure
 *            exact mass conservation: H + He + Z_total = 0
 */

