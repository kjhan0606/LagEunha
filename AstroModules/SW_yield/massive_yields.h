static inline const YieldTableEntry* get_wind_yield_table(int feh) {
    switch (feh) {
        case  0: return g_wind_yields_solar;
        case -1: return g_wind_yields_z0002;
        case -2: return g_wind_yields_z00002;
        case -3: return g_wind_yields_z000002;
        default: return (void*)0;
    }
}

static inline double interp_wind_yield(const YieldTableEntry* table, double mass, ElementIndex elem) {
    int i;
    for (i = 0; i < N_GWIND_MASS_BINS - 1; i++) if (mass <= table[i + 1].mass) break;
    if (mass <= table[0].mass) return table[0].yields[elem];
    if (mass >= table[N_GWIND_MASS_BINS - 1].mass) return table[N_GWIND_MASS_BINS - 1].yields[elem];
    double t = (mass - table[i].mass) / (table[i + 1].mass - table[i].mass);
    return table[i].yields[elem] + t * (table[i + 1].yields[elem] - table[i].yields[elem]);
}

